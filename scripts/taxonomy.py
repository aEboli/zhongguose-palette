"""中国传统色分类体系：色系、五行、四季、色调、物象来源、设计角色。

分类原则（重要，直接影响检索质量）：
色名优先于色值。中国色名自带古人的归类判断——"鲛青"实测偏墨绿，但古人叫它青，
它在织物语境里就是青。所以先按名字末字定色系，再用实测色相校正明显冲突
（名叫灰而彩度很高，或名末字不是色词）。

五行/四季属于文化语法，不是物理事实。它们的用途是给配色提供一套"古人认可的
搭配理由"（相生为和、相克为冲），而不是宣称某个色号必须属于某一行。
"""

from __future__ import annotations

# ---------------------------------------------------------------- 色系

# 末字 -> 色系。按传统色名习惯归并：褐/啡/驼/综 皆入棕，绯/朱 入红。
SUFFIX_FAMILY = {
    "黄": "黄", "橙": "橙", "红": "红", "绯": "红", "朱": "红", "粉": "粉",
    "紫": "紫", "蓝": "蓝", "青": "青", "绿": "绿",
    "棕": "棕", "褐": "棕", "啡": "棕", "驼": "棕", "综": "棕",
    "白": "白", "灰": "灰",
}

# 末字不是色词的特例，按物象本色手工指定，避免落进"其他"。
SPECIAL_FAMILY = {
    "肉色": "粉", "淡肉色": "粉", "醉瓜肉": "粉", "米色": "白",
    "驼色": "棕", "浅驼色": "棕", "槟榔综": "棕", "淡赭": "棕", "赭石": "棕",
    "豆沙": "棕", "淡豆沙": "棕", "淡松烟": "灰", "银朱": "红",
    "藕荷": "粉", "青莲": "紫", "汉白玉": "白", "淡绯": "红",
}

# 色相角（LCH H）-> 色系，作为色值兜底。区间按 CIELAB 色相排布，
# 与 HSL 不同：LCH 里黄在 90° 左右、蓝在 260-300°。
HUE_FAMILY_BANDS = [
    (0, 20, "红"), (20, 45, "橙"), (45, 75, "棕"), (75, 110, "黄"),
    (110, 150, "绿"), (150, 200, "绿"), (200, 250, "青"), (250, 300, "蓝"),
    (300, 340, "紫"), (340, 360, "红"),
]


def family_from_hue(h: float, c: float, l: float) -> str:
    """按 LCH 色相定色系；低彩度先归中性。"""
    if c < 6.0:
        return "白" if l >= 82 else "灰" if l >= 22 else "黑"
    if c < 14.0 and l >= 88:
        return "白"
    h %= 360.0
    for lo, hi, fam in HUE_FAMILY_BANDS:
        if lo <= h < hi:
            # 高明度低彩的红紫区实为粉
            if fam in ("红", "紫") and l >= 72 and c < 45:
                return "粉"
            return fam
    return "灰"


def family_of(name: str, h: float, c: float, l: float) -> tuple[str, str, str]:
    """返回 (最终色系, 名义色系, 色值色系)。

    冲突消解：名义色系为准，除非它是中性词（白/灰）而实测彩度明显（C>=22），
    这类如"玫瑰灰""中红灰"确实带色，检索时按色值归族更有用。
    """
    hue_fam = family_from_hue(h, c, l)
    name_fam = SPECIAL_FAMILY.get(name) or SUFFIX_FAMILY.get(name[-1], "")
    if not name_fam:
        return hue_fam, "", hue_fam
    final = name_fam
    # 名叫白/灰但实测彩度很高（C>=35）才改判：莲子白 C=23 仍是纸感奶油，
    # 尘灰 C=26 仍是卡其灰，只有真正带色的"灰"（如未来出现的高彩灰）才改。
    if name_fam in ("白", "灰") and c >= 35.0:
        final = hue_fam
    # 名叫彩色但实测近无彩：马鞭草紫 C=4 实为粉白，苷蓝绿 C=4 实为近黑。
    if name_fam not in ("白", "灰", "黑") and c < 5.0:
        final = hue_fam
    return final, name_fam, hue_fam


