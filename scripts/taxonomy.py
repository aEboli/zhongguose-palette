# 正色五色的标准指认（用于判断某色是否近于正色）
ZHENGSE = {"青": "木", "赤": "火", "黄": "土", "白": "金", "黑": "水"}


def wuxing_of(family: str, l: float, c: float, name: str) -> str:
    """按色系 + 明度定五行归属。

    间色（紫/棕/粉/灰）无正色位置，依其倾向就近归并：
    紫本为"赤黑相加"，故深紫归水、浅紫近粉归火；
    灰白按明度分金水，与"金主洁、水主玄"对应。
    """
    if family == "紫":
        return "火" if l >= 62 and c >= 18 else "水"
    if family in ("灰", "白"):
        return "金" if l >= 58 else "水"
    if family == "蓝":
        return "水" if l < 45 else "木"
    if family == "绿" and l < 24:
        return "水"
    if family == "橙":
        return "火" if c >= 55 else "土"
    if l <= 16:
        return "水"
    return WUXING_BASE.get(family, "土")


