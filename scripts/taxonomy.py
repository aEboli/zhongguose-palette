# 色词本身不作为物象来源。"灰"是颜色而非草木灰，"青灰""深灰"若靠它归类，
# 会把 44 条来源判断里的 30 条冲成器用类。
_COLOR_WORDS = frozenset("红黄蓝绿紫黑白灰橙粉青棕褐赤丹绯朱靛缃黛玄")


def source_of(name: str) -> str:
    """判断色名的物象来源。取最长命中词，避免"石榴红"被"石"抢走。"""
    best, best_len = "", 0
    for cat, keys in SOURCE_KEYWORDS.items():
        for k in keys:
            if len(k) == 1 and k in _COLOR_WORDS:
                continue
            if k in name and len(k) > best_len:
                best, best_len = cat, len(k)
    return best or "抽象色名"


# ---------------------------------------------------------------- 设计角色

def roles_of(family: str, l: float, c: float, contrast_white: float,
             contrast_black: float, name: str) -> list[str]:
    """给每个颜色打设计角色标签，供配色时按用途筛选。

    这是把色卡变成可用色板的关键一步：526 个色平铺出来没法选，
    但"能当浅底的那几十个""能当正文墨色的那几十个"是可以直接决策的。
    阈值对齐 WCAG 2.2：正文需 4.5:1，大字与 UI 部件需 3:1。
    """
    tags: list[str] = []
    # 底色：大面积铺陈，必须低彩，否则铺开后会视觉过载
    if l >= 88 and c <= 20:
        tags.append("浅底")
    if l >= 82 and c <= 32:
        tags.append("纸感")
    if l <= 26:
        tags.append("深底")
    # 承载内容的中间层
    if 62 <= l < 90 and c <= 26:
        tags.append("面层")
    # 文字色：以能否在白底/黑底上达标为准
    if contrast_white >= 4.5:
        tags.append("浅底可作正文")
    if contrast_white >= 3.0:
        tags.append("浅底可作大字")
    if contrast_black >= 4.5:
        tags.append("深底可作正文")
    if l <= 32 and c <= 30:
        tags.append("墨色")
    # 点缀：只有够艳才撑得起最小面积的分量
    if c >= 45:
        tags.append("点缀")
    if c >= 62:
        tags.append("强点缀")
    # 分隔线与描边：需要与底色拉开一点，但不能抢戏
    if 42 <= l < 82 and c <= 24:
        tags.append("描边")
    # 中性调和色：配色里最缺的一类，用来兜住两个彩色
    if c <= 12:
        tags.append("中性")
    if 12 < c <= 26:
        tags.append("带色中性")
    # 文化材质角色
    if any(k in name for k in ("金", "银", "铜", "铁", "锡", "锌", "镍", "钢", "鼎")):
        tags.append("金属")
    if any(k in name for k in ("瓷", "釉", "琉璃", "青花", "汝", "钧", "哥", "定")):
        tags.append("瓷器")
    if any(k in name for k in ("墨", "烟", "砚", "笔", "宣")):
        tags.append("水墨")
    return tags


# ---------------------------------------------------------------- 冷暖

def temperature_of(w: float) -> str:
    """把连续冷暖值离散成五档标签。"""
    if w >= 0.55:
        return "暖"
    if w >= 0.18:
        return "偏暖"
    if w > -0.18:
        return "中性"
    if w > -0.55:
        return "偏冷"
    return "冷"
